#!/bin/bash
# Regenerates gateway_frames.inc from the core's own Java encoders. Run after a money schema re-pin, with the core
# cluster jar built from the commit dependencies.lock pins (money_schema_ref):
#   tests/golden/regen.sh <core-cluster.jar>
# The jar's META-INF/MANIFEST.MF Build-Sha must name money_schema_ref and its sbe/money-schema.xml must have the
# money_schema_sha256 of the lock; any other jar is refused, because it would regenerate the goldens from an unpinned
# encoder. The C++ side never writes this file.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
JAVA_OPTS=(--add-opens java.base/jdk.internal.misc=ALL-UNNAMED)

[ $# -eq 1 ] || { echo "usage: $0 <core-cluster.jar>" >&2; exit 64; }
JAR=$1

want=$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1])).get("money_schema_ref", ""))' \
    "$ROOT/dependencies.lock")
if ! [[ "$want" =~ ^[0-9a-f]{40}$ ]]; then
    echo "FATAL: dependencies.lock money_schema_ref is not a 40-hex commit: '$want'" >&2
    exit 1
fi
# the schema inside the jar must be the one the lock pins, byte for byte: a jar rebuilt with an edited schema keeps
# its Build-Sha
want_schema=$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1])).get("money_schema_sha256", ""))' \
    "$ROOT/dependencies.lock")
if ! [[ "$want_schema" =~ ^[0-9a-f]{64}$ ]]; then
    echo "FATAL: dependencies.lock money_schema_sha256 is not a 64-hex digest: '$want_schema'" >&2
    exit 1
fi
got=$(unzip -p "$JAR" META-INF/MANIFEST.MF 2>/dev/null | tr -d '\r' | sed -n 's/^Build-Sha: *//p' | head -n1 || true)
if ! [[ "$got" =~ ^[0-9a-f]{40}$ ]] || [ "$got" != "$want" ]; then
    echo "FATAL: core jar $JAR has Build-Sha '${got:-<missing>}', dependencies.lock money_schema_ref is $want;" \
        "refusing to regenerate" >&2
    exit 1
fi

got_schema=$(unzip -p "$JAR" sbe/money-schema.xml 2>/dev/null | sha256sum | cut -d' ' -f1 || true)
if ! unzip -l "$JAR" sbe/money-schema.xml >/dev/null 2>&1 || [ "$got_schema" != "$want_schema" ]; then
    echo "FATAL: core jar $JAR carries sbe/money-schema.xml with sha256 '${got_schema:-<missing>}'," \
        "dependencies.lock money_schema_sha256 is $want_schema; refusing to regenerate" >&2
    exit 1
fi

{
    echo "// GENERATED by tests/golden/regen.sh from the core's Java encoders. Do not edit."
    echo "// core: Build-Sha $got"
    echo "static const char *const GOLDEN_CORE_BUILD_SHA = \"$got\";"
    java "${JAVA_OPTS[@]}" -cp "$JAR" "$HERE/GoldenGateway.java"
} > "$HERE/gateway_frames.inc.tmp"
mv "$HERE/gateway_frames.inc.tmp" "$HERE/gateway_frames.inc"
echo "wrote $HERE/gateway_frames.inc"
